#!/usr/bin/env python3
"""Regenerates Data/Recipes.lua and Data/QuestItems.lua from Forever Ledger's data files, and merges the learn skills,
colour thresholds and sources of ProfessionsTracker into the recipes.

Sources (MIT, see NOTICE and THIRD-PARTY):
  Forever Ledger  https://github.com/ivellos/forever-ledger  (pinned commit below; --fl DIR reads a local copy instead)
  ProfessionsTracker 1.2.0 by Thork, unzipped to a folder holding Data.lua and Data2.lua: python3 tools/build-data.py --pt DIR
The Forever Ledger commit is recorded in the header of each generated file.
"""
import argparse, re, urllib.request, pathlib

REPO = "ivellos/forever-ledger"
SHA = "25c02308da21ded6396a459a7de08aa498822df0"
PT_VERSION = "1.2.0"
ROOT = pathlib.Path(__file__).resolve().parent.parent

ap = argparse.ArgumentParser()
ap.add_argument("--pt", required=True, help="folder with ProfessionsTracker's Data.lua and Data2.lua")
ap.add_argument("--fl", help="local copy of Forever Ledger at the pinned commit (default: download it)")
args = ap.parse_args()

def get(url):
    with urllib.request.urlopen(url, timeout=60) as r:
        return r.read().decode("utf-8")

sha = SHA
raw = (lambda name: (pathlib.Path(args.fl) / name).read_text(encoding="utf-8")) if args.fl else \
    (lambda name: get(f"https://raw.githubusercontent.com/{REPO}/{sha}/{name}"))

# --- ProfessionsTracker: { profession: { English recipe name: { s, y, g, gr, src } } }
PT_SRC = {"vendor": "v", "rep": "v", "book": "v", "quest": "q", "drop": "d"}  # trainer = no source (assumed trainer)
pt = {}
pt_trainers, pt_npcs = {}, {}
STR = r'"(?:[^"\\]|\\.)*"'
def lua_str(tok): return tok[1:-1].replace('\\"', '"').replace("\\\\", "\\")
for fname in ("Data.lua", "Data2.lua"):
    text_all = (pathlib.Path(args.pt) / fname).read_text(encoding="utf-8")
    # trainers: D.Trainers = { ["Prof"] = { ... } } (Data.lua) and D.Trainers["Prof"] = { ... } (Data2.lua)
    tprof, in_trainers = None, False
    for line in text_all.splitlines():
        if line.startswith("D.Trainers = {"): in_trainers = True
        if line.startswith("D.Recipes") or line.startswith("D.NPCs"): in_trainers = False
        m = re.match(r'^D\.Trainers\["([^"]+)"\] = \{', line)
        if m: tprof, in_trainers = m.group(1), True
        h = re.match(r'^\s+\["([^"]+)"\] = \{\s*$', line) if in_trainers and fname == "Data.lua" else None
        if h: tprof = h.group(1)
        t = re.match(r'^\s*\{ n = "([^"]+)", +zone = "([^"]+)", +x = ([\d.]+), +y = ([\d.]+), +f = (?:"([AH])"|nil), +top = "([^"]+)"', line) if in_trainers and tprof else None
        if t: pt_trainers.setdefault(tprof, []).append((t.group(1), t.group(2), float(t.group(3)), float(t.group(4)), t.group(5), t.group(6)))
    # NPCs (vendors, quest givers): ["Name"] = { zone = "...", x = 1, y = 2, f = "A" }
    for m in re.finditer(r'^\s+\["([^"]+)"\]\s*= \{ zone = "([^"]+)", +x = ([\d.]+), +y = ([\d.]+)(?:, f = "([AH])")? \}', text_all, re.M):
        pt_npcs[m.group(1)] = (m.group(2), float(m.group(3)), float(m.group(4)), m.group(5))
    lvars = dict(re.findall(r'^local ([A-Z]+) = (' + STR + ')', text_all, re.M))
    prof, inside = None, fname == "Data2.lua"
    for line in text_all.splitlines():
        if line.startswith("D.Recipes = {"): inside = True
        head = re.match(r'^(?:D\.Recipes)?\s*\["([^"]+)"\] = \{', line) if inside else None
        if head: prof = head.group(1)
        m = re.match(r'^\s*\{ n = "([^"]+)",(.*)$', line) if inside and prof else None
        if m and "src =" in m.group(2):
            f = {k: int(v) for k, v in re.findall(r'\b(s|y|g|gr) = (\d+)', m.group(2))}
            f["src"] = re.search(r'src = "(\w+)"', m.group(2)).group(1)
            wm = re.search(r'\bw = ((?:' + STR + r'|[A-Z]+)(?:\s*\.\.\s*(?:' + STR + r'|[A-Z]+))*)', m.group(2))
            if wm:
                toks = re.findall(STR + r'|[A-Z]+', wm.group(1))
                f["w"] = "".join(lua_str(t) if t.startswith('"') else lua_str(lvars[t]) for t in toks)
            pt.setdefault(prof, {})[m.group(1).lower()] = f

# --- crafts (Forever, from Wago client data via Forever Ledger) + recipe sources (Classic, unconfirmed on Forever)
crafts = raw("ForeverCrafts.lua")
rows = re.findall(r'\{ id = (\d+), prof = "([^"]+)", skill = (\d+), out = (\d+), low = (\d+), high = (\d+), sell = (\d+), n = "([^"]*)", r = \{ ((?:\{ \d+, \d+ \}(?:, )?)+) \}', crafts)
sources = {}
for m in re.finditer(r'\["([^"]+)"\] = \{ item = (\d+), skill = (\d+), kind = "(\w+)"', raw("ClassicRecipes.lua")):
    sources[m.group(1)] = (m.group(4), int(m.group(3)))
KIND = {"vendor": "v", "mob": "m", "drop": "d", "quest": "q"}

out = [
    "-- GENERATED by tools/build-data.py. Do not edit by hand.",
    f"-- Vendored data copied from Forever Ledger (https://github.com/{REPO}, MIT licence, see NOTICE), commit {sha}.",
    "-- Crafts come from Forever Ledger's ForeverCrafts.lua (client data, Forever 1.60.1); recipe sources (src, learn)",
    "-- come from its ClassicRecipes.lua (original Classic data, NOT confirmed on Forever). src: v vendor, m mob drop,",
    "-- d other drop, q quest, nil = assumed trainer. learn = skill needed to learn the recipe.",
    f"-- Learn skills, colour thresholds (yellow, green, gray) and missing sources are merged by name from ProfessionsTracker {PT_VERSION}",
    "-- by Thork (https://www.curseforge.com/wow/addons/profession-tracker-forever, MIT licence, see NOTICE), also Classic data,",
    "-- NOT confirmed on Forever. `skill` (column 3) is not a reliable level: use learn.",
    "-- Row: { craftSpellID, profession, skill, outputItem, outLow, outHigh, vendorSell, name, \"mat:count,...\", src, learn, yellow, green, gray }",
    "local _, ns = ...",
    "ns.RecipeRows = {",
]
matched = withLearn = merged = 0
where = {}
for rid, prof, skill, o, low, high, sell, name, mats in rows:
    flat = ",".join(f"{a}:{b}" for a, b in re.findall(r"\{ (\d+), (\d+) \}", mats))
    src = sources.get(name.lower())
    matched += bool(src)
    kind, learn = (KIND[src[0]], src[1]) if src else (None, None)
    extra = pt.get(prof, {}).get(name.lower())
    thresholds = ""
    if extra:
        merged += 1
        if not learn and extra.get("s") and extra["src"] != "unknown": learn = extra["s"]  # "unknown" = not taught the vanilla way
        if not kind: kind = PT_SRC.get(extra["src"])
        if all(k in extra for k in ("y", "g", "gr")): thresholds = f', {extra["y"]}, {extra["g"]}, {extra["gr"]}'
    withLearn += bool(learn)
    if extra and extra.get("w") and (kind or extra["src"] == "unknown") and extra["src"] != "trainer":
        where[rid] = extra["w"]
    tail = f', {chr(34) + kind + chr(34) if kind else "nil"}, {learn}{thresholds}' if learn else ""
    out.append(f'  {{ {rid}, "{prof}", {skill}, {o}, {low}, {high}, {sell}, "{name}", "{flat}"{tail} }},')
out.append("}")
(ROOT / "Data/Recipes.lua").write_text("\n".join(out) + "\n", encoding="utf-8")
# --- locations: trainers, NPCs and the "where" text of recipes, from ProfessionsTracker (Classic data, not confirmed on Forever)
RANK = {"Journeyman": 1, "Expert": 2, "Artisan": 3}  # other tops are specialisations
def q(x): return '"' + x.replace("\\", "\\\\").replace('"', '\\"') + '"'
loc = [
    "-- GENERATED by tools/build-data.py. Do not edit by hand.",
    f"-- Trainers, NPC positions and recipe 'where' texts from ProfessionsTracker {PT_VERSION} by Thork",
    "-- (https://www.curseforge.com/wow/addons/profession-tracker-forever, MIT licence, see NOTICE). Original Classic data,",
    "-- NOT confirmed on Forever. Zone names are English (see ns.MapIDs in Data/Zones.lua); x, y are map percentages.",
    "-- ns.Trainers[profession] = { { name, zone, x, y, faction (A, H or nil), rank (1 Journeyman, 2 Expert, 3 Artisan, 0 specialisation) }, ... }",
    "-- ns.NPCs[name] = { zone, x, y, faction }   (vendors, quest givers and book sellers; positions 0,0 are left out)",
    "-- ns.RecipeWhere[craftSpellID] = { where text, npc name, ... } for recipes that are not taught by a trainer",
    "local _, ns = ...",
    "ns.Trainers = {",
]
ntr = 0
for prof in sorted(pt_trainers):
    loc.append(f"  [{q(prof)}] = {{")
    for n, zone, x, y, f, top in pt_trainers[prof]:
        ntr += 1
        loc.append(f"    {{ {q(n)}, {q(zone)}, {x}, {y}, {q(f) if f else 'nil'}, {RANK.get(top, 0)} }},")
    loc.append("  },")
loc += ["}", "ns.NPCs = {"]
npcs = {n: v for n, v in pt_npcs.items() if v[1] > 0 and v[2] > 0}
for n in sorted(npcs):
    z, x, y, f = npcs[n]
    loc.append(f"  [{q(n)}] = {{ {q(z)}, {x}, {y}, {q(f) if f else 'nil'} }},")
loc += ["}", "ns.RecipeWhere = {"]
for rid in sorted(where, key=int):
    names = [n for n in sorted(npcs) if n in where[rid]]
    loc.append(f"  [{rid}] = {{ {', '.join(q(x) for x in [where[rid]] + names)} }},")
loc.append("}")
(ROOT / "Data/Locations.lua").write_text("\n".join(loc) + "\n", encoding="utf-8")
print(f"Locations: {ntr} trainers, {len(npcs)} NPCs, {len(where)} recipe locations")
print(f"Recipes: {len(rows)} crafts, {matched} with a Classic source, {merged} matched in ProfessionsTracker, {withLearn} with a learn skill")

# --- quest items: quest, zone, level, faction, { item name, count, ... } resolved to item IDs
ids = {}
for m in re.finditer(r'\[(\d+)\] = "((?:[^"\\]|\\.)*)"', raw("ClassicItems.lua")):
    ids.setdefault(m.group(2).lower(), int(m.group(1)))
quests = {}
unresolved = 0
for m in re.finditer(r'^  \{ "([^"]+)", "([^"]+)", (\d+), "([ABH])", \{ ([^}]*) \}', raw("QuestItems.lua"), re.M):
    quest, zone, level, faction, items = m.groups()
    for name, count in re.findall(r'"([^"]+)", (\d+)', items):
        iid = ids.get(name.lower())
        if not iid:
            unresolved += 1
            continue
        quests.setdefault(iid, []).append(f'{{ quest = "{quest}", zone = "{zone}", level = {level}, faction = "{faction}", count = {count} }}')
q = [
    "-- GENERATED by tools/build-data.py. Do not edit by hand.",
    f"-- Vendored data copied from Forever Ledger's QuestItems.lua (https://github.com/{REPO}, MIT licence, see NOTICE),",
    f"-- commit {sha}. Item names were resolved to IDs with its ClassicItems.lua. Original Classic quests, not confirmed on Forever.",
    "-- ns.QuestItems[itemID] = { { quest =, zone = (English), level =, faction = (A, H or B), count = }, ... }",
    "local _, ns = ...",
    "ns.QuestItems = {",
]
for iid in sorted(quests):
    q.append(f"  [{iid}] = {{ {', '.join(quests[iid])} }},")
q.append("}")
(ROOT / "Data/QuestItems.lua").write_text("\n".join(q) + "\n", encoding="utf-8")
print(f"QuestItems: {len(quests)} items, {unresolved} names unresolved")
