#!/usr/bin/env python3
"""Regenerates Data/Recipes.lua and Data/QuestItems.lua from Forever Ledger's data files.

Source: https://github.com/ivellos/forever-ledger (MIT licence, see NOTICE). Run: python3 tools/build-data.py
The commit used is recorded in the header of each generated file.
"""
import json, re, urllib.request, pathlib

REPO = "ivellos/forever-ledger"
ROOT = pathlib.Path(__file__).resolve().parent.parent

def get(url):
    with urllib.request.urlopen(url, timeout=60) as r:
        return r.read().decode("utf-8")

sha = json.loads(get(f"https://api.github.com/repos/{REPO}/commits/main"))["sha"]
raw = lambda name: get(f"https://raw.githubusercontent.com/{REPO}/{sha}/{name}")

# --- crafts (Forever, from Wago client data via Forever Ledger) + recipe sources (Classic, unconfirmed on Forever)
crafts = raw("ForeverCrafts.lua")
rows = re.findall(r'\{ id = (\d+), prof = "([^"]+)", skill = (\d+), out = (\d+), low = (\d+), high = (\d+), sell = (\d+), n = "([^"]*)", r = \{ ((?:\{ \d+, \d+ \}(?:, )?)+) \}', crafts)
sources = {}
for m in re.finditer(r'\["([^"]+)"\] = \{ item = (\d+), skill = (\d+), kind = "(\w+)"', raw("ClassicRecipes.lua")):
    sources[m.group(1)] = (m.group(4), int(m.group(3)))
KIND = {"vendor": "v", "mob": "m", "drop": "d", "quest": "q"}

out = [
    "-- GENERATED by tools/build-data.py. Do not edit by hand.",
    f"-- Vendored data copied from Forever Ledger (https://github.com/{REPO}, MIT licence, see NOTICE), commit {sha}.",
    "-- Crafts come from Forever Ledger's ForeverCrafts.lua (client data, Forever 1.60.1); recipe sources (src, learn)",
    "-- come from its ClassicRecipes.lua (original Classic data, NOT confirmed on Forever). src: v vendor, m mob drop,",
    "-- d other drop, q quest, nil = assumed trainer. learn = skill needed to learn the recipe.",
    "-- Row: { craftSpellID, profession, skill, outputItem, outLow, outHigh, vendorSell, name, \"mat:count,...\", src, learn }",
    "local _, ns = ...",
    "ns.RecipeRows = {",
]
matched = 0
for rid, prof, skill, o, low, high, sell, name, mats in rows:
    flat = ",".join(f"{a}:{b}" for a, b in re.findall(r"\{ (\d+), (\d+) \}", mats))
    src = sources.get(name.lower())
    matched += bool(src)
    tail = f', "{KIND[src[0]]}", {src[1]}' if src else ""
    out.append(f'  {{ {rid}, "{prof}", {skill}, {o}, {low}, {high}, {sell}, "{name}", "{flat}"{tail} }},')
out.append("}")
(ROOT / "Data/Recipes.lua").write_text("\n".join(out) + "\n", encoding="utf-8")
print(f"Recipes: {len(rows)} crafts, {matched} with a Classic source")

# --- quest items: quest, zone, level, faction, { item name, count, ... } resolved to item IDs
ids = {}
for m in re.finditer(r'\[(\d+)\] = "((?:[^"\\]|\\.)*)"', raw("ClassicItems.lua")):
    ids.setdefault(m.group(2).lower(), int(m.group(1)))
quests = {}
unresolved = 0
for m in re.finditer(r'^  \{ "([^"]+)", "([^"]+)", (\d+), "([ABH])", \{ ([^}]*) \}', raw("QuestItems.lua"), re.M):
    quest, zone, level, faction, items = m.groups()
    for name, count in re.findall(r'"([^"]+)", (\d+)', items):
        iid = ids.get(name.lower())
        if not iid:
            unresolved += 1
            continue
        quests.setdefault(iid, []).append(f'{{ quest = "{quest}", zone = "{zone}", level = {level}, faction = "{faction}", count = {count} }}')
q = [
    "-- GENERATED by tools/build-data.py. Do not edit by hand.",
    f"-- Vendored data copied from Forever Ledger's QuestItems.lua (https://github.com/{REPO}, MIT licence, see NOTICE),",
    f"-- commit {sha}. Item names were resolved to IDs with its ClassicItems.lua. Original Classic quests, not confirmed on Forever.",
    "-- ns.QuestItems[itemID] = { { quest =, zone = (English), level =, faction = (A, H or B), count = }, ... }",
    "local _, ns = ...",
    "ns.QuestItems = {",
]
for iid in sorted(quests):
    q.append(f"  [{iid}] = {{ {', '.join(quests[iid])} }},")
q.append("}")
(ROOT / "Data/QuestItems.lua").write_text("\n".join(q) + "\n", encoding="utf-8")
print(f"QuestItems: {len(quests)} items, {unresolved} names unresolved")
