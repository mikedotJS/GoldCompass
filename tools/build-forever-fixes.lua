-- Builds Data/ForeverFixes.lua: the recipe values of the Forever client (ForeverDB.net's extraction of the current build, the cache of
-- tools/build-foreverdb.py) wherever they differ from what Gold Compass would show from its other sources (LibProfessionDB, wowforever.be,
-- Forever Ledger). Only the differences are written, so the file stays small and says exactly what was corrected.
-- Run from the repo, after tools/build-foreverdb.py: lua tools/build-forever-fixes.lua tools/cache-foreverdb
-- tools/audit-forever.lua measures the agreement before and after. The downloaded files are loaded as text chunks with an empty
-- environment (data only). Licence of the data: GPL-3.0 with the attribution term, credit "Data from ForeverDB.net" (see NOTICE).
local dir = arg[1]
local F = {}
for _, f in ipairs({ "Recipes", "Meta", "Gather" }) do assert(loadfile(dir .. "/" .. f .. ".lua", "t", {}))("ForeverDB", F) end
local ns = {}
for _, f in ipairs({ "Strings", "Data/Zones", "Data/Recipes", "Data/Locations", "Data/ForeverTrainers", "Data/ForeverRecipes", "Data/Npcs", "Data/GatherNodes",
  "Data/ForeverNpcs", "ZoneRank", "ForeverDB", "Leveling", "Where" }) do
  assert(loadfile(f .. ".lua"))("GoldCompass", ns)
end
local LINES = { [171] = "Alchemy", [164] = "Blacksmithing", [333] = "Enchanting", [202] = "Engineering", [165] = "Leatherworking",
  [197] = "Tailoring", [185] = "Cooking", [129] = "First Aid", [356] = "Fishing", [393] = "Skinning", [186] = "Mining", [182] = "Herbalism" }
local fdb = {}
for _, rows in pairs(F.recipes) do for _, r in ipairs(rows) do fdb[r[1]] = r end end

local gone, learn, th, oq, fee, feeDoubt = {}, {}, {}, {}, {}, {}
for line, english in pairs(LINES) do
  if ns.ForeverDB:HasProfession(line) then
    local byId = {}
    for _, c in ipairs(ns.Leveling.Crafts(ns.RecipeRows, english)) do byId[c.id] = c end
    -- what the addon would show without any fix
    for _, c in ipairs(ns.Leveling.LibCrafts(ns.ForeverDB, line, "H", function(id) return byId[id] end, ns.ForeverTrainers)) do
      local r, id = fdb[c.id], c.id
      if not r then
        -- not a recipe of the Forever client; the rank books (a vendor sells their teaching item) are not recipes there either and stay
        if not (ns.FdbVendors and ns.FdbVendors[id]) then gone[id] = true end
      else
        local info, ft = F.recipeInfo[id] or {}, ns.ForeverTrainers[id]
        -- skill needed: the client's own value (r[13] == 1 marks ForeverDB's Classic trainer data, 0 = it has none)
        if r[13] ~= 1 and r[3] > 0 and c.learn ~= r[3] then learn[id] = r[3] end
        if r[4] > 0 and r[5] > 0 and r[6] > 0 and (c.y ~= r[4] or c.g ~= r[5] or c.gr ~= r[6]) then th[id] = { r[4], r[5], r[6] } end
        if r[8] > 0 and c.oq ~= r[8] then oq[id] = r[8] end
        -- trainer fee: two observers up to 20 % apart saw one price with and without a reputation discount (5 to 20 %): the full price
        -- is the higher one. Further apart, the two sources really disagree: the site's fee stays, marked as not verified.
        if ft and ft.cost and info.tc and info.tc ~= ft.cost then
          local ratio = math.min(ft.cost, info.tc) / math.max(ft.cost, info.tc)
          if ratio < 0.8 then feeDoubt[id] = true elseif info.tc > ft.cost then fee[id] = info.tc end
        end
      end
    end
  end
end

-- what a node gives: the items of Data/GatherNodes.lua (hand-maintained, Classic) that ForeverDB's gathering data does not have for
-- any node (the fishing pools, three quest ores): the pairing node -> item is not verified on Forever
local gathered, gatherDoubt = {}, {}
for _, k in pairs(F.gatherData.kinds) do if k.item then gathered[k.item] = true end end
for _, g in pairs(ns.GatherNodes) do if g.item and not gathered[g.item] then gatherDoubt[g.item] = true end end

local function keys(t) local k = {}; for id in pairs(t) do k[#k + 1] = id end; table.sort(k); return k end
local function flat(name, t, fmt)
  local parts = {}
  for _, id in ipairs(keys(t)) do parts[#parts + 1] = ("[%d] = %s"):format(id, fmt(t[id])) end
  return ("  %s = { %s },"):format(name, table.concat(parts, ", "))
end
local num = function(v) return (("%g"):format(v)) end
local out = {
  "-- GENERATED by tools/build-forever-fixes.lua. Do not edit by hand.",
  ("-- Data from ForeverDB.net (https://foreverdb.net), game build %s, data version %s: the Forever client's own recipe values, only where"):format(F.meta.build, F.meta.version),
  "-- they differ from what Gold Compass would show from its other sources. Licence of this file's data: GPL-3.0 with an attribution term",
  "-- (section 7(b)), see NOTICE and THIRD-PARTY. tools/audit-forever.lua measures the agreement.",
  "-- gone: listed by the library but not a recipe of the Forever client (never listed); learn: skill needed to learn; th: { yellow, green,",
  "-- gray } thresholds; oq: crafted quantity (the average when it is random); fee: trainer fee before any reputation discount; feeDoubt:",
  "-- the two sources give trainer fees too far apart to be one price with a discount (the fee shown is not verified); gatherDoubt:",
  "-- items of Data/GatherNodes.lua that ForeverDB's gathering data gives to no node (what the node gives is not verified on Forever).",
  "local _, ns = ...",
  "ns.ForeverFixes = {",
  flat("gone", gone, function() return "true" end),
  flat("learn", learn, num),
  flat("th", th, function(v) return ("{ %d, %d, %d }"):format(v[1], v[2], v[3]) end),
  flat("oq", oq, num),
  flat("fee", fee, num),
  flat("feeDoubt", feeDoubt, function() return "true" end),
  flat("gatherDoubt", gatherDoubt, function() return "true" end),
  "}",
}
local h = assert(io.open("Data/ForeverFixes.lua", "w"))
h:write(table.concat(out, "\n"), "\n")
h:close()
