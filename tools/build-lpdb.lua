-- Builds Data/ForeverRecipes.lua from the WoW Forever data of LibProfessionDB (v1.10.1, by Pimptasty, MIT).
-- Run (from the addon folder): lua tools/build-lpdb.lua <ProfessionDB folder> > Data/ForeverRecipes.lua
-- It loads the library's own file and its Data/Forever/_core files into the real library (so merges, true totals and
-- borrowed flags are the library's own), then writes only what Gold Compass reads, compactly: no locale names (only the
-- English name of a recipe Data/Recipes.lua does not have, as a last-resort label), no
-- trainer NPC ids, no drop NPC ids (only that a kind exists), vendor and quest NPCs with names, faction and price.
local dir = assert(arg[1], "usage: lua tools/build-lpdb.lua <ProfessionDB folder>")
local VERSION, BUILD = "v1.10.1", "1.60.1.70938"

function GetLocale() return "enUS" end
function GetBuildInfo() return "1.60.1", "70938", "Nov 14 2026", 16001 end   -- the Forever client: library picks its Forever tree
dofile(dir .. "/libs/LibStub/LibStub.lua")
dofile(dir .. "/LibProfessionDB-1.0.lua")
local lib = LibStub("LibProfessionDB-1.0")
assert(lib:GetGameVersion() == "Forever")
for _, f in ipairs({ "Alchemy", "Blacksmithing", "Cooking", "Enchanting", "Engineering", "Firstaid", "Fishing", "Herbalism",
  "Leatherworking", "Mining", "Skinning", "Tailoring", "RecipeItems", "HiddenRecipes", "AcquireMethods", "Sources", "SourceNames",
  "VendorSources" }) do
  dofile(dir .. "/Data/Forever/_core/" .. f .. ".lua")
end
for _, f in ipairs({ "Alchemy", "Blacksmithing", "Cooking", "Enchanting", "Engineering", "Firstaid", "Fishing", "Herbalism",
  "Leatherworking", "Mining", "Skinning", "Tailoring" }) do
  dofile(dir .. "/Data/Forever/enUS/" .. f .. ".lua")
end
local have = {}   -- recipes of Data/Recipes.lua: their English name is already there
local data = {}
loadfile("Data/Recipes.lua")("GoldCompass", data)
for _, r in ipairs(data.RecipeRows) do have[r[1]] = true end
local names = {}

-- recipes whose vendors are Forever's OWN (seen on live merchants, VendorSources.lua): the library still lists them as borrowed
local ownVendor = {}
local vs = assert(io.open(dir .. "/Data/Forever/_core/VendorSources.lua")):read("a")
for id in vs:sub(1, vs:find("lib:LoadSourceNames", 1, true) - 1):gmatch("\n%[(%d+)%]={v=") do ownVendor[tonumber(id)] = true end

local out = {}
local function w(s) out[#out + 1] = s end
local function sortedKeys(t) local k = {}; for key in pairs(t) do k[#k + 1] = key end; table.sort(k); return k end
local function q(s) return '"' .. s:gsub("\\", "\\\\"):gsub('"', '\\"') .. '"' end

w("-- GENERATED by tools/build-lpdb.lua. Do not edit by hand.")
w("-- Source: LibProfessionDB " .. VERSION .. " by Pimptasty (https://www.curseforge.com/wow/addons/professiondb), MIT licence (see NOTICE and")
w("-- THIRD-PARTY), WoW Forever data of build " .. BUILD .. ", vendored so no other addon is needed. Only what Gold Compass reads;")
w("-- recipe names come from the game (English fallbacks: Data/Recipes.lua). Read it through ns.ForeverDB (ForeverDB.lua).")
w("-- recipes[skillLine] = { { spellID, requiredSkill (0 = none), orange, yellow, green, gray, craftedItem (0 = none),")
w("--   \"item:count,...\" reagents, teachingItem (0 = none), flags }, ... } with flags h hidden (never implemented), a granted with the")
w("--   profession, r requiredSkill borrowed from Vanilla, s sources borrowed from Vanilla, x hidden flag borrowed, o vendors seen on live Forever merchants.")
w("-- src[spellID] = \"tvqcd\" kinds (trainer, vendor, quest, container, drop) or { kinds, { vendor NPC ids }, { quest NPC ids } }.")
w("-- name[spellID] = English name of a recipe Data/Recipes.lua lacks (last-resort label; the game's own name wins).")
w("-- npc[id] = English name, faction[id] = \"A\"|\"H\" (vendors only one faction can use), cost[spellID][npcID] = parts")
w("-- { c = currency, n = amount } | { i = item, n = amount } | { g = copper }.")
w("local _, ns = ...")
w("ns.ForeverData = { version = " .. q(VERSION) .. ", build = " .. q(BUILD) .. ", recipes = {")

local KIND = { { "trainer", "t" }, { "vendor", "v" }, { "quest", "q" }, { "container", "c" }, { "drop", "d" } }
local used, srcOut, count = {}, {}, 0
local lines = {}
for _, line in ipairs(sortedKeys(lib.recipes)) do lines[#lines + 1] = line end
for _, line in ipairs(lines) do
  w("  [" .. line .. "] = {")
  for _, id in ipairs(sortedKeys(lib.recipes[line])) do
    local e = lib.recipes[line][id]
    local d = e.difficulty or { 1, 1, 1, 1 }
    local mats = {}
    for item, n in pairs(e.reagents or {}) do mats[#mats + 1] = item end
    table.sort(mats)
    for i, item in ipairs(mats) do mats[i] = item .. ":" .. e.reagents[item] end
    local flags = (lib:IsHiddenRecipe(id) and "h" or "") .. (lib:IsAutoTaughtRecipe(id) and "a" or "")
      .. (lib:IsBorrowed(id, "requiredSkill") and "r" or "") .. (lib:IsBorrowed(id, "sources") and "s" or "")
      .. (lib:IsBorrowed(id, "hidden") and "x" or "") .. (ownVendor[id] and "o" or "")
    assert(e.requiredSkill ~= 0)
    w(("    { %d, %d, %d, %d, %d, %d, %d, %q, %d, %q },"):format(id, e.requiredSkill or 0, d[1], d[2], d[3], d[4],
      e.craftedItemId or 0, table.concat(mats, ","), (lib:GetRecipeItem(id)) or 0, flags))
    count = count + 1
    if not have[id] and e.name then names[id] = e.name end
    local s = lib:GetRecipeSources(id)
    if s then
      local kinds, v, qs = "", {}, {}
      for _, k in ipairs(KIND) do if s[k[1]] then kinds = kinds .. k[2] end end
      for _, n in ipairs(s.vendor or {}) do v[#v + 1] = n.id; used[n.id] = true end
      for _, n in ipairs(s.quest or {}) do qs[#qs + 1] = n.id; used[n.id] = true end
      srcOut[id] = (#v + #qs == 0) and kinds or { kinds, v, qs }
    end
  end
  w("  },")
end
w("}, src = {")
for _, id in ipairs(sortedKeys(srcOut)) do
  local s = srcOut[id]
  if type(s) == "string" then w(("  [%d] = %q,"):format(id, s))
  else w(("  [%d] = { %q, { %s }, { %s } },"):format(id, s[1], table.concat(s[2], ", "), table.concat(s[3], ", "))) end
end
w("}, name = {")
for _, id in ipairs(sortedKeys(names)) do w(("  [%d] = %s,"):format(id, q(names[id]))) end
w("}, npc = {")
for _, id in ipairs(sortedKeys(used)) do
  local name = lib:GetSourceName(id)
  if name then w(("  [%d] = %s,"):format(id, q(name))) end
end
w("}, faction = {")
for _, id in ipairs(sortedKeys(used)) do
  local f = lib:GetSourceFaction(id)
  if f then w(("  [%d] = %q,"):format(id, f:sub(1, 1))) end
end
w("}, cost = {")
for _, spell in ipairs(sortedKeys(lib.vendorCosts)) do
  local parts = {}
  for _, npc in ipairs(sortedKeys(lib.vendorCosts[spell])) do
    local ps = {}
    for _, p in ipairs(lib.vendorCosts[spell][npc]) do
      local f = {}
      for _, key in ipairs({ "c", "i", "g", "n" }) do if p[key] then f[#f + 1] = key .. " = " .. p[key] end end
      ps[#ps + 1] = "{ " .. table.concat(f, ", ") .. " }"
    end
    parts[#parts + 1] = ("[%d] = { %s }"):format(npc, table.concat(ps, ", "))
  end
  w(("  [%d] = { %s },"):format(spell, table.concat(parts, ", ")))
end
w("} }")
io.write(table.concat(out, "\n"), "\n")
io.stderr:write(("recipes: %d, with sources: %d, NPCs named: %d\n"):format(count, #sortedKeys(srcOut), #sortedKeys(used)))
